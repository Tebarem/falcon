// falcon_schemagen: shared ECS component schema -> C++ header + C# source.
//   falcon_schemagen <schema.fschema> <out.h> <out.cs>
// Outputs are only rewritten when their content changes (keeps builds incremental).

#include <cctype>
#include <algorithm>
#include <cstdio>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

namespace {

struct Type {
    const char* name;
    const char* cpp;
    const char* cs;
    unsigned size, align;
};

const Type kTypes[] = {
    {"f32", "float", "float", 4, 4},           {"u32", "uint32_t", "uint", 4, 4},
    {"i32", "int32_t", "int", 4, 4},           {"u64", "uint64_t", "ulong", 8, 8},
    {"f32x3", "float3", "Vector3", 12, 4},     {"f32x4", "float4", "Vector4", 16, 4},
};

struct Field {
    const Type* type;
    std::string name;
    unsigned count = 1;  // > 1: fixed array
    std::vector<std::string> comments;
};

struct Component {
    std::string name;
    std::vector<Field> fields;
    std::vector<std::string> comments;
    unsigned size = 0, align = 1;
    std::vector<unsigned> offsets;
};

std::string cString(const std::string& s)
{
    std::string out = "\"";
    for (const char c : s)
        out += c == '"' || c == '\\' ? std::string("\\") + c : std::string(1, c);
    return out + "\"";
}

bool writeIfChanged(const std::string& path, const std::string& text)
{
    std::ifstream in(path, std::ios::binary);
    if (in) {
        std::stringstream old;
        old << in.rdbuf();
        if (old.str() == text)
            return true;
    }
    std::ofstream out(path, std::ios::binary | std::ios::trunc);
    out << text;
    return bool(out);
}

std::string trim(const std::string& s)
{
    const size_t a = s.find_first_not_of(" \t\r"), b = s.find_last_not_of(" \t\r");
    return a == std::string::npos ? std::string() : s.substr(a, b - a + 1);
}

}  // namespace

int main(int argc, char** argv)
{
    if (argc != 4) {
        std::fprintf(stderr, "usage: falcon_schemagen <schema.fschema> <out.h> <out.cs>\n");
        return 2;
    }
    std::ifstream in(argv[1]);
    if (!in) {
        std::fprintf(stderr, "falcon_schemagen: cannot read %s\n", argv[1]);
        return 1;
    }
    std::vector<Component> components;
    std::vector<std::string> pending;  // comments for the next field/component
    bool header = true;                 // the file's leading comment block is not copied
    std::string line;
    for (int lineNo = 1; std::getline(in, line); ++lineNo) {
        const std::string t = trim(line);
        if (t.empty()) {
            header = false;
            pending.clear();
            continue;
        }
        if (t[0] == '#') {
            if (!header)
                pending.push_back(trim(t.substr(1)));
            continue;
        }
        header = false;
        std::istringstream words(t);
        std::string a, b;
        words >> a >> b;
        if (a == "component") {
            components.push_back({b, {}, pending});
            pending.clear();
            continue;
        }
        if (components.empty()) {
            std::fprintf(stderr, "%s:%d: field outside a component\n", argv[1], lineNo);
            return 1;
        }
        const Type* type = nullptr;
        for (const Type& k : kTypes)
            if (a == k.name)
                type = &k;
        if (!type || b.empty()) {
            std::fprintf(stderr, "%s:%d: expected '<type> <name>' (types: f32 u32 i32 u64 f32x3 f32x4)\n", argv[1], lineNo);
            return 1;
        }
        Field f{type, b, 1, pending};
        pending.clear();
        if (const size_t br = b.find('['); br != std::string::npos) {
            f.name = b.substr(0, br);
            f.count = unsigned(std::stoul(b.substr(br + 1)));
            if (type->cs[0] < 'a') {  // fixed buffers only take primitives
                std::fprintf(stderr, "%s:%d: arrays must be of a scalar type\n", argv[1], lineNo);
                return 1;
            }
        }
        components.back().fields.push_back(f);
    }

    std::ostringstream h, cs;
    h << "#pragma once\n\n// Generated by falcon_schemagen from engine/scene/components.fschema. Do not edit.\n\n"
         "#include \"core/math.h\"\n\n#include <cstddef>\n#include <cstdint>\n\nnamespace fx {\n";
    cs << "// Generated by falcon_schemagen from engine/scene/components.fschema. Do not edit.\n\n"
          "using System.Numerics;\nusing System.Runtime.InteropServices;\n\nnamespace Falcon;\n";
    for (Component& c : components) {
        // Sequential layout with natural alignment, identical in C++ and C#.
        unsigned offset = 0;
        std::vector<unsigned> offsets;
        for (const Field& f : c.fields) {
            offset = (offset + f.type->align - 1) / f.type->align * f.type->align;
            offsets.push_back(offset);
            offset += f.type->size * f.count;
            c.align = std::max(c.align, f.type->align);
        }
        c.size = (offset + c.align - 1) / c.align * c.align;
        c.offsets = offsets;

        h << "\n";
        for (const std::string& s : c.comments)
            h << "// " << s << "\n";
        h << "struct " << c.name << " {\n";
        for (const Field& f : c.fields) {
            for (const std::string& s : f.comments)
                h << "    // " << s << "\n";
            h << "    " << f.type->cpp << " " << f.name;
            if (f.count > 1)
                h << "[" << f.count << "]";
            h << ";\n";
        }
        h << "    static constexpr const char* kComponentName = \"" << c.name << "\";\n};\n";
        h << "static_assert(sizeof(" << c.name << ") == " << c.size << ");\n";
        for (size_t i = 0; i < c.fields.size(); ++i)
            h << "static_assert(offsetof(" << c.name << ", " << c.fields[i].name << ") == " << offsets[i] << ");\n";

        cs << "\n";
        for (const std::string& s : c.comments)
            cs << "/// <summary>" << s << "</summary>\n";
        cs << "[Component(\"" << c.name << "\"), StructLayout(LayoutKind.Sequential, Size = " << c.size << ")]\n";
        cs << "public unsafe partial struct " << c.name << "\n{\n";
        for (const Field& f : c.fields) {
            for (const std::string& s : f.comments)
                cs << "    /// <summary>" << s << "</summary>\n";
            if (f.count > 1)
                cs << "    public fixed " << f.type->cs << " " << f.name << "[" << f.count << "];\n";
            else
                cs << "    public " << f.type->cs << " " << f.name << ";\n";
        }
        // Three or four floats also as a vector (Size for size[3]), so scripts change them without unsafe code.
        for (const Field& f : c.fields) {
            if (std::string(f.type->cs) != "float" || (f.count != 3 && f.count != 4))
                continue;
            std::string prop = f.name;
            prop[0] = char(std::toupper(static_cast<unsigned char>(prop[0])));
            const std::string& n = f.name;
            const bool four = f.count == 4;
            cs << "\n    /// <summary>" << n << " as a " << (four ? "Vector4" : "Vector3") << ".</summary>\n";
            cs << "    public " << (four ? "Vector4 " : "Vector3 ") << prop << "\n    {\n";
            cs << "        readonly get => new(" << n << "[0], " << n << "[1], " << n << "[2]" << (four ? ", " + n + "[3]" : "") << ");\n";
            cs << "        set\n        {\n";
            cs << "            " << n << "[0] = value.X;\n            " << n << "[1] = value.Y;\n            " << n << "[2] = value.Z;\n";
            if (four)
                cs << "            " << n << "[3] = value.W;\n";
            cs << "        }\n    }\n";
        }
        cs << "}\n";
    }
    // Reflection for tools (the editor's inspector): every component's fields.
    h << "\n// Field layout of every component, for tools (the editor's inspector).\n"
         "struct ComponentFieldInfo {\n    const char* name;\n    const char* type;  // schema type: f32 u32 i32 u64 f32x3 f32x4\n"
         "    uint32_t offset, count;\n};\n"
         "struct ComponentInfo {\n    const char* name;\n    const char* doc;\n    uint32_t size;\n"
         "    const ComponentFieldInfo* fields;\n    uint32_t fieldCount;\n};\n";
    for (const Component& c : components) {
        h << "inline constexpr ComponentFieldInfo k" << c.name << "Fields[] = {";
        for (size_t i = 0; i < c.fields.size(); ++i)
            h << (i ? ", " : "") << "{" << cString(c.fields[i].name) << ", \"" << c.fields[i].type->name << "\", "
              << c.offsets[i] << ", " << c.fields[i].count << "}";
        h << "};\n";
    }
    h << "inline constexpr ComponentInfo kComponentInfos[] = {\n";
    for (const Component& c : components) {
        std::string doc;
        for (const std::string& s : c.comments)
            doc += (doc.empty() ? "" : " ") + s;
        h << "    {" << cString(c.name) << ", " << cString(doc) << ", " << c.size << ", k" << c.name << "Fields, "
          << c.fields.size() << "},\n";
    }
    h << "};\n";
    h << "\n}  // namespace fx\n";

    if (!writeIfChanged(argv[2], h.str()) || !writeIfChanged(argv[3], cs.str())) {
        std::fprintf(stderr, "falcon_schemagen: cannot write outputs\n");
        return 1;
    }
    return 0;
}
